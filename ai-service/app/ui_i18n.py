    val = UI_CATALOG.get(lang_code, {}).get(key)
    if not val:
        val = UI_CATALOG.get("en", {}).get(key, key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            # Fallback formatting using English string if target language placeholder failed
            fallback_val = UI_CATALOG.get("en", {}).get(key, key)
            try:
                return fallback_val.format(**kwargs)
            except Exception:
                return val
    return val


